// Build the browser bundle: concatenate the authored client sources into the
// module-loader factory the DSH web host serves at /plugins/<package>/client.js.
//
// Authored files are plain ES2020 + React.createElement (no JSX, no bundler):
//
//   src/client.base.js    shared atoms / CSS / project rail / setup wizard
//   src/client.review.js  outline + document views, markdown renderer, chat dock
//   src/client.app.js     App state machine, API client, slot registration
//
// Because all three are concatenated into ONE factory closure, later files can
// call functions/constants declared earlier (and hoisted function declarations
// declared later). Keep the concatenation order fixed.
//
//   node build.js

import { mkdir, readFile, writeFile } from "node:fs/promises";

const ROOT = new URL(".", import.meta.url);
const ID = "@jichong/dsh-doc-creator";
const PARTS = ["src/client.base.js", "src/client.review.js", "src/client.app.js"];

const chunks = [];
for (const part of PARTS) {
	const source = await readFile(new URL(part, ROOT), "utf8");
	chunks.push(`// ───── ${part} ─────\n${source.replace(/\s+$/, "")}\n`);
}

const body = chunks
	.join("\n")
	.split("\n")
	.map((line) => (line.length > 0 ? `\t\t${line}` : ""))
	.join("\n");

const bundle = `// GENERATED by build.js from src/client.base.js, src/client.review.js, src/client.app.js — do not edit.
window.__ModuleLoader__.load({
	id: ${JSON.stringify(ID)},
	factory: (require) => {
		var module = { exports: {} };
		var exports = module.exports;
		Object.defineProperty(exports, Symbol.toStringTag, { value: "Module" });
${body}
		return module.exports;
	}
});
`;

await mkdir(new URL("lib/", ROOT), { recursive: true });
await writeFile(new URL("lib/client.js", ROOT), bundle, "utf8");
console.log(`built lib/client.js (${bundle.length} bytes)`);
